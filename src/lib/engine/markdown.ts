import type { DriftReport, PageAnalysis, Severity } from "./schema";

/** Markdown export of a report, matching the CLI's `--output report.md` shape. */
export function reportToMarkdown(report: DriftReport, shareUrl?: string): string {
  const lines: string[] = [];
  lines.push(`# msgdrift report: ${report.site}`);
  lines.push("");
  lines.push(`Overall alignment: **${Math.round(report.overallScore)}/100** (pages that could not be read are left out)`);
  lines.push(`Findings: ${report.counts.critical} critical, ${report.counts.major} major, ${report.counts.minor} minor, ${report.counts.info} info`);
  lines.push(`Scanned ${report.pages.length} page${report.pages.length === 1 ? "" : "s"} on ${new Date(report.createdAt).toUTCString()} with ${report.model}.`);
  if (shareUrl) lines.push(`Share link: ${shareUrl}`);
  lines.push("");
  lines.push("## Executive summary");
  lines.push("");
  lines.push(report.executiveSummary || "_No summary._");
  lines.push("");
  lines.push("## Pages");
  lines.push("");
  lines.push("| Page | Importance | Score | Findings |");
  lines.push("|---|---|---|---|");
  for (const p of report.pages) {
    const score = p.error ? "not read" : String(Math.round(p.alignmentScore));
    lines.push(`| [${escapePipes(p.label || p.url)}](${p.url}) | ${p.importance} | ${score} | ${p.findings.length} |`);
  }
  lines.push("");
  for (const p of report.pages) lines.push(...pageSection(p));
  lines.push("---");
  lines.push("Generated by [msgdrift](https://msgdrift.com), semantic messaging drift detection built on Claude.");
  return lines.join("\n");
}

function pageSection(p: PageAnalysis): string[] {
  const out: string[] = [];
  out.push(`### ${p.label || p.url}`);
  out.push("");
  out.push(`${p.url}  `);
  out.push(`Importance: ${p.importance} · Score: ${p.error ? "not read" : `${Math.round(p.alignmentScore)}/100`}`);
  out.push("");
  out.push(p.error ? `This page was not read and is left out of the overall score. ${p.error}` : p.summary);
  out.push("");
  if (!p.findings.length) {
    out.push(p.error ? "_Not read._" : "_No drift findings._");
    out.push("");
    return out;
  }
  const order: Severity[] = ["critical", "major", "minor", "info"];
  const sorted = [...p.findings].sort((a, b) => order.indexOf(a.severity) - order.indexOf(b.severity));
  for (const f of sorted) {
    out.push(`#### ${f.severity.toUpperCase()} · ${f.category}`);
    out.push("");
    out.push(`**On the page:** "${f.pageExcerpt}"`);
    out.push("");
    out.push(`**In the positioning:** "${f.sourceExcerpt}"`);
    out.push("");
    out.push(f.explanation);
    out.push("");
  }
  return out;
}

function escapePipes(s: string): string {
  return s.replace(/\|/g, "\\|");
}
